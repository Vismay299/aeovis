import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseSkillFile } from "../src/assistant/skills/frontmatter.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS_DIR = path.join(ROOT, "src", "assistant", "skills");
const MANIFEST_PATH = path.join(SKILLS_DIR, "manifest.generated.ts");
const LOCK_PATH = path.join(SKILLS_DIR, "versions.lock.json");
const STALE = "assistant skills manifest is stale; run npm run skills:build";

const sha256 = (text) => createHash("sha256").update(text).digest("hex");

function skillFolders() {
  return readdirSync(SKILLS_DIR)
    .filter((entry) => statSync(path.join(SKILLS_DIR, entry)).isDirectory())
    .filter((entry) => existsSync(path.join(SKILLS_DIR, entry, "SKILL.md")))
    .sort();
}

function readLock() {
  if (!existsSync(LOCK_PATH)) return {};
  return JSON.parse(readFileSync(LOCK_PATH, "utf8"));
}

function build(previousLock) {
  const entries = [];
  for (const folder of skillFolders()) {
    const file = path.join("src", "assistant", "skills", folder, "SKILL.md");
    const raw = readFileSync(path.join(ROOT, file), "utf8");
    const normalised = raw.replace(/\r\n/g, "\n");
    const { frontmatter, body } = parseSkillFile(file, normalised);
    if (frontmatter.name !== folder) {
      throw new Error(`${file}: folder "${folder}" must match frontmatter name "${frontmatter.name}"`);
    }
    const title = /^# (.+)$/.exec(body.split("\n")[0])[1].trim();
    entries.push({ ...frontmatter, sha256: sha256(normalised), body, title });
  }

  // The lock covers exactly the skills on disk. A new skill records its current hash. An existing
  // skill keeps its recorded hash unless its version changed, so an edit without a bump is caught by
  // versions.test.ts. A deleted skill's entry is dropped with it.
  const lock = {};
  for (const entry of entries) {
    const previous = previousLock[entry.name];
    lock[entry.name] =
      previous && previous.version === entry.version
        ? { version: entry.version, sha256: previous.sha256 }
        : { version: entry.version, sha256: entry.sha256 };
  }
  const sortedLock = Object.fromEntries(Object.keys(lock).sort().map((key) => [key, lock[key]]));

  const fingerprint = sha256(entries.map((entry) => entry.sha256).join("\n"));
  const manifest = [
    "// GENERATED by scripts/build-assistant-skills.mjs. Do not edit; run `npm run skills:build`.",
    'import type { SkillManifestEntry } from "./types.ts";',
    "",
    "export const SKILL_MANIFEST: readonly SkillManifestEntry[] = [",
    ...entries.map((entry) => `  ${JSON.stringify(entry)},`),
    "];",
    "",
    `export const SKILL_MANIFEST_FINGERPRINT = ${JSON.stringify(fingerprint)};`,
    "",
  ].join("\n");

  return { manifest, lock: `${JSON.stringify(sortedLock, null, 2)}\n` };
}

const mode = process.argv[2];
if (mode !== "--write" && mode !== "--check") {
  console.error("usage: build-assistant-skills.mjs --write | --check");
  process.exit(2);
}

const { manifest, lock } = build(readLock());

if (mode === "--check") {
  const currentManifest = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, "utf8") : "";
  if (currentManifest !== manifest) {
    console.error(STALE);
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(MANIFEST_PATH, manifest);
writeFileSync(LOCK_PATH, lock);
console.log(`wrote ${path.relative(ROOT, MANIFEST_PATH)} and ${path.relative(ROOT, LOCK_PATH)}`);
